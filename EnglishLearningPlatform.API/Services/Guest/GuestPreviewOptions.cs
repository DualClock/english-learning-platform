namespace EnglishLearningPlatform.API.Services.Guest;

/// <summary>
/// Настройки гостевого чтения. Вынесены в отдельный класс, чтобы политика
/// «сколько текста видит гость» была одной строкой, которую видно в
/// конфигурации, а не разбросанной по контроллеру магической константой.
///
/// Здесь намеренно НЕТ опции «сколько глав»: ровно одна, всегда первая.
/// Параметр, которым можно расширить превью до всей книги, рано или поздно
/// будет выставлен в деплое «на пару дней», и публичный текст останется
/// публичным навсегда. Если понадобится больше — это изменение кода с ревью.
/// </summary>
public sealed class GuestPreviewOptions
{
    public const string SectionName = "GuestPreview";

    /// <summary>
    /// Потолок на число блоков первой главы в ответе. Глава романа — это
    /// 60–200 блоков, рассказ — десятки; потолок нужен не для экономии, а как
    /// предохранитель на случай EPUB с одной гигантской главой на всю книгу
    /// (тогда «глава 1» и есть вся книга, а гость не должен получить её).
    /// </summary>
    public int MaxBlocksPerChapter { get; set; } = 240;

    /// <summary>
    /// Бюджет WordLevels-запросов на слово. Каждое слово — поиск по ключу
    /// Text, но каскад «слово, лемма, регулярные формы» превращает один
    /// клик в десяток запросов: бюджет ограничивает худший случай, а точное
    /// совпадение и первая лемма проверяются всегда.
    /// </summary>
    public int MaxWordLookupQueries { get; set; } = 4;

    /// <summary>Кэш перевода: тот же счётчик, что у публичного каталога (6 ч).</summary>
    public TimeSpan WordCacheTtl { get; set; } = TimeSpan.FromHours(6);
}
