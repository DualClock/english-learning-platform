namespace EnglishLearningPlatform.API.Models;

/// <summary>
/// Контент, который админ «удаляет» из интерфейса, но который обязан остаться
/// в базе.
///
/// Почему не физическое удаление: у пользователей уже есть прогресс, ссылающийся
/// на эти строки. Слово в SRS-колоде, слово в категории, книга на полке — всё
/// это чужие данные, и DELETE строки источника их либо уносит каскадом, либо
/// оставляет висячие внешние ключи.
///
/// Формат: DeletedAt + DeletedByUserId, а не IsDeleted. Время отвечает на
/// «когда вышло из обихода», автор — на «кто это сделал»; оба нужны при разборе
/// «почему у меня пропало слово». Восстановление — обнуление обоих полей.
/// </summary>
public interface ISoftDeletable
{
    DateTime? DeletedAt { get; set; }

    string? DeletedByUserId { get; set; }
}
