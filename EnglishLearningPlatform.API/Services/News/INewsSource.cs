namespace EnglishLearningPlatform.API.Services.News;

/// <summary>
/// Один источник новостей (RSS/Atom/HTML-страница конкретного сайта).
///
/// Почему интерфейс, а не базовый класс: источников будет несколько, они разные
/// по природе (лента RSS против скрейпинга страницы), и общего кода, кроме
/// «отдай записи», между ними нет. Фетчер ничего не знает ни про один из них —
/// он получает IEnumerable&lt;INewsSource&gt; и опрашивает всех.
///
/// Контракт намеренно узкий. Источник не пишет в базу и не знает про DbContext:
/// иначе скрейпер пришлось бы тащить в тесты вместе с БД, а дедупликация
/// размазалась бы по всем источникам. Уборка, дедупликация и санитизация HTML —
/// забота NewsFetchService.
/// </summary>
public interface INewsSource
{
    /// <summary>
    /// Имя источника для журнала и для колонки SourceName, если запись его
    /// не указала. Не бросает: недоступная лента — это исключение из метода
    /// FetchAsync, которое фетчер ловит и логирует.
    /// </summary>
    string Name { get; }

    /// <summary>
    /// Забрать актуальные записи фида.
    ///
    /// Может бросить что угодно (DNS, таймаут, разбор, HTML без разметки) —
    /// тот, кто вызывает, обязан изолировать каждый источник от остальных:
    /// упавший фид не должен отменять записи соседей.
    /// </summary>
    Task<IReadOnlyList<NewsFeedEntry>> FetchAsync(CancellationToken ct);
}
