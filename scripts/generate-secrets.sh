#!/usr/bin/env bash
# Генератор сильных значений для секретов Lexicon.
#
# Печатает KEY=value в stdout и НИКУДА не пишет: ни в файлы, ни в историю,
# ни в git. Перенаправление в файл — решение человека, и оно почти всегда
# ошибочно (файл уедет в бэкап, в rsync, в архив тикета). Правильный путь:
#        bash scripts/generate-secrets.sh   ->  скопировать в менеджер секретов
#
# В самом скрипте нет ни одного значения — только имена переменных и длины,
# поэтому его можно безопасно держать в публичном репозитории.
#
# Сгенерированные значения живут в выводе терминала: после копирования
# в менеджер секретов очистите буфер обмена и историю (см. SECRET_ROTATION.md).

set -euo pipefail

# Соль/ключ из одного алфавита (base64) содержит «+», «/» и «=», и это ломает
# то, что не ждёт таких символов: systemd EnvironmentFile читает значение как
# строку и не интерполирует, но значения с пробелом/кавычкой трактуются иначе.
# Соль для хеша IP ходит через JSON-конфиг (Analytics__GuestIpSalt) — там base64
# безопасен, однако используем hex ради однообразия с тем, что уже на сервере.
need() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ОШИБКА: не найдено '$1'. Нужен openssl (входит в git-bash и в любой Linux)." >&2
    exit 1
  }
}
need openssl

# base64 без переводов строк: одна длинная строка, её удобно копировать целиком.
b64() { openssl rand -base64 "$1" | tr -d '\n'; }

emit() {
  local name="$1" value="$2" min_len="$3" purpose="$4"
  if [ "${#value}" -lt "$min_len" ]; then
    echo "ОШИБКА: $name короче $min_len символов" >&2
    exit 1
  fi
  printf '# %s (минимум %s символов, сгенерировано %s)\n' \
    "$purpose" "$min_len" "${#value}"
  printf '%s=%s\n\n' "$name" "$value"
}

cat >&2 <<'BANNER'
=== Lexicon: генерация секретов ===
Вывод содержит боевые секреты. Скопируйте значения в менеджер секретов и
очистите буфер обмена. НЕ перенаправляйте вывод в файл в рабочем дереве:
такой файл уедет в git, в rsync на сервер и в бэкап.
BANNER

# NEXTAUTH_SECRET: подписывает/шифрует JWT-сессию NextAuth. 48 байт энтропии
# (64 base64-символа) — с запасом; next-auth сам требует «достаточно длинный»,
# точную планку не навязывает, поэтому берём верхнюю практичную.
emit NEXTAUTH_SECRET "$(b64 48)" 64 "Подпись сессии фронтенда (next-auth)"

# Jwt__Key: HMAC-SHA256 подпись access-токена API. Программа отвергает ключи
# короче 32 символов (Program.cs), стартующая с SET_IN_ENV — тоже.
emit Jwt__Key "$(b64 48)" 64 "Подпись access-токена API (HMAC-SHA256)"

# Seeder__Key: X-Seed-Key для служебных эндпоинтов (сиды контента, сводка
# аналитики). Пустой ключ в Production закрывает доступ, но в Development
# ОТКРЫВАЕТ его (AdminKeyGuard.IsAuthorized) — поэтому ключ обязателен всегда.
emit Seeder__Key "$(b64 32)" 43 "X-Seed-Key: сиды контента и сводка аналитики"

# Feedback__AdminKey: отдельный ключ страницы /admin/feedback. Отдельный
# намеренно: Seeder__Key читает сид-контент, и смешивать его с личными
# отзывами пользователей — значит отдавать отзывы любому, кто знает сид-ключ.
emit Feedback__AdminKey "$(b64 32)" 43 "X-Seed-Key: страница отзывов /admin/feedback"

# Analytics__GuestIpSalt: соль хеша IP в воронке /test. Пустая = случайный
# ключ процесса, и тогда «уникальные гости за сутки» не сходятся между
# рестартами. 32 hex-символа (16 байт) достаточно: это не пароль, а соль.
emit Analytics__GuestIpSalt "$(openssl rand -hex 32)" 64 "Соль хеша IP в гостевой воронке /test"

cat >&2 <<'FOOTER'
=== Готово ===
Дальше: docs/execution/SECRET_ROTATION.md — там порядок выкладки значений,
перезапуск без простоя и проверка, что старые сессии больше не принимаются.
FOOTER
